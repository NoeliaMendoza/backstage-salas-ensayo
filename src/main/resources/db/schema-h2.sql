CREATE TABLE IF NOT EXISTS bandas (
 id UUID PRIMARY KEY, codigo VARCHAR(9) NOT NULL UNIQUE,
 nombre VARCHAR(60) NOT NULL, genero_musical VARCHAR(255) NOT NULL,
 correo_representante VARCHAR(255) NOT NULL, numero_integrantes INTEGER NOT NULL,
 activa BOOLEAN NOT NULL
);
CREATE TABLE IF NOT EXISTS salas (
 id UUID PRIMARY KEY, nombre VARCHAR(80) NOT NULL, capacidad INTEGER NOT NULL,
 tarifa_hora DECIMAL(12,2) NOT NULL, descripcion_equipo VARCHAR(500) NOT NULL,
 habilitada BOOLEAN NOT NULL
);
CREATE TABLE IF NOT EXISTS reservas (
 id UUID PRIMARY KEY, banda_id UUID NOT NULL REFERENCES bandas(id),
 sala_id UUID NOT NULL REFERENCES salas(id), fecha DATE NOT NULL,
 hora_inicio TIME NOT NULL, duracion_horas INTEGER NOT NULL CHECK (duracion_horas BETWEEN 1 AND 6),
 total DECIMAL(12,2) NOT NULL, estado VARCHAR(20) NOT NULL,
 creada_en TIMESTAMP(9) WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_reservas_banda_fecha ON reservas(banda_id, fecha);
CREATE INDEX IF NOT EXISTS idx_reservas_sala_fecha ON reservas(sala_id, fecha);
CREATE TABLE IF NOT EXISTS auditoria (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 accion VARCHAR(80) NOT NULL, fecha TIMESTAMP(9) WITH TIME ZONE NOT NULL
);
